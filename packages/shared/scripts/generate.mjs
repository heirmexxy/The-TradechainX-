#!/usr/bin/env node
// Generates typed ABIs and deployment addresses for the apps from the Foundry build output.
// Uses only Node built-ins. Run after `forge build` and after every deployment:
//   node packages/shared/scripts/generate.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const out = join(root, "contracts", "out");
const deploymentsDir = join(root, "contracts", "deployments");
const abiDir = join(here, "..", "src", "abis");

// [Solidity file, contract name, exported TS name]
const CONTRACTS = [
  ["IdentityRegistry.sol", "IdentityRegistry", "identityRegistryAbi"],
  ["WarehouseRegistry.sol", "WarehouseRegistry", "warehouseRegistryAbi"],
  ["WarehouseReceipt.sol", "WarehouseReceipt", "warehouseReceiptAbi"],
  ["LPOToken.sol", "LPOToken", "lpoTokenAbi"],
  ["CarbonCredits.sol", "CarbonCredits", "carbonCreditsAbi"],
  ["Marketplace.sol", "Marketplace", "marketplaceAbi"],
  ["XOwnFactory.sol", "XOwnFactory", "xownFactoryAbi"],
  ["XOwnVault.sol", "XOwnVault", "xownVaultAbi"],
  ["XOwnEquipment.sol", "XOwnEquipment", "xownEquipmentAbi"],
  ["MockUSDC.sol", "MockUSDC", "mockUsdcAbi"],
];

if (!existsSync(out)) {
  console.error("contracts/out not found — run `forge build` in contracts/ first.");
  process.exit(1);
}

mkdirSync(abiDir, { recursive: true });
const header = "// AUTO-GENERATED by packages/shared/scripts/generate.mjs from contracts/out. Do not edit.\n";
const index = [header];

for (const [file, name, exportName] of CONTRACTS) {
  const artifactPath = join(out, file, `${name}.json`);
  const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"));
  const moduleName = exportName.replace(/Abi$/, "");
  writeFileSync(
    join(abiDir, `${moduleName}.ts`),
    `${header}export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${exportName} } from "./${moduleName}.ts";`);
  console.log(`abi  ${name.padEnd(20)} ${abi.length} entries`);
}
writeFileSync(join(abiDir, "index.ts"), index.join("\n") + "\n");

// Deployments: contracts/deployments/<chainId>.json → one typed map.
const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const f of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, f), "utf8"));
    deployments[d.chainId] = d;
    console.log(`addr chain ${d.chainId}`);
  }
}
writeFileSync(
  join(here, "..", "src", "deployments.ts"),
  `${header}
export type Deployment = {
  chainId: number;
  startBlock: number;
  usdc: \`0x\${string}\`;
  identityRegistry: \`0x\${string}\`;
  warehouseRegistry: \`0x\${string}\`;
  warehouseReceipt: \`0x\${string}\`;
  lpoToken: \`0x\${string}\`;
  carbonCredits: \`0x\${string}\`;
  marketplace: \`0x\${string}\`;
  xownFactory: \`0x\${string}\`;
  xownEquipment: \`0x\${string}\`;
};

export const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};

export function getDeployment(chainId: number): Deployment {
  const d = deployments[chainId];
  if (!d) throw new Error(\`No TradeChainX deployment for chain \${chainId}. Deploy, then run \\\`pnpm generate\\\`.\`);
  return d;
}
`,
);
console.log("done");
